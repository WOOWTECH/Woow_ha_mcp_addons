"""0.2.2: the packaged tools/list snapshot (mcp_admin_core/tool_snapshot.py) the gateway answers with when no child can
answer (no backend configured, or a child that is not up), kept equal to the real pinned children.

The snapshot is each child's own tools/list tools, listed with every tool enabled against a fake backend, reduced to
the members the gateway relays (name, title, description, inputSchema, annotations; policy.listed_tool), in the child's
order. After a child upgrade the comparison here fails until the snapshot is regenerated from the real children:

    WOOW_WRITE_TOOL_SNAPSHOT=1 .venv/bin/python -m pytest -q tests/test_tool_snapshot.py

(the regenerated file is then reviewed like any other change; surface.py must classify every name first).
"""
import asyncio
from contextlib import closing
import os
from pathlib import Path
import pprint

import httpx
import pytest

from mcp_admin_core.gateway import make_apps
from mcp_admin_core.products import ProductStore, TOOLS, child_spec, health_probe
from mcp_admin_core.surface import BACKEND_FREE, FULL_PRODUCTS, listing, names
from mcp_admin_core.tool_snapshot import LISTED
from n8n_adapter import TOOLS as N8N_TOOLS, child_spec as n8n_spec
from owned_runtime import Endpoint
from test_expansion_runtime import fake_api
from test_real_products import connection, rpc

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / 'packages/mcp-admin-core/mcp_admin_core/tool_snapshot.py'
KEPT = ('name', 'title', 'description', 'inputSchema', 'annotations')
ACCEPT = {'Accept': 'application/json, text/event-stream'}
INIT = {'jsonrpc': '2.0', 'id': 1, 'method': 'initialize', 'params': {
    'protocolVersion': '2025-03-26', 'capabilities': {}, 'clientInfo': {'name': 'snapshot-test', 'version': '0'}}}
HEADER = '''"""GENERATED by tests/test_tool_snapshot.py from the real pinned children; do not edit by hand.

0.2.2: each child's tools/list tools with every tool enabled (name, title, description, inputSchema, annotations, in the
child's order), which the gateway answers tools/list with when no child can answer (surface.listing). Regenerate with
WOOW_WRITE_TOOL_SNAPSHOT=1 .venv/bin/python -m pytest -q tests/test_tool_snapshot.py
"""
'''


def tools_of(product):
    return N8N_TOOLS if product == 'n8n' else TOOLS[product]


def reduced(product, tools):
    """The child's listed tools the snapshot keeps: classified names only (never a private health probe), relayed
    members only."""
    return [{key: tool[key] for key in KEPT if key in tool} for tool in tools if tool['name'] in tools_of(product)]


def write_snapshot(product, tools):
    listed = dict(LISTED)
    listed[product] = tools
    ordered = {name: listed[name] for name in FULL_PRODUCTS if name in listed}
    SNAPSHOT.write_text(HEADER + 'LISTED = ' + pprint.pformat(ordered, width=120, sort_dicts=False) + '\n')
    LISTED[product] = tools


def test_snapshot_names_are_the_classified_surface():
    assert tuple(LISTED) == FULL_PRODUCTS
    for product in FULL_PRODUCTS:
        listed = [tool['name'] for tool in LISTED[product]]
        assert len(listed) == len(set(listed)), product
        classified = [name for group in names(product).values() for name in group]
        assert set(listed) == set(tools_of(product)) == set(classified), product
        assert all(set(tool) <= set(KEPT) and isinstance(tool.get('inputSchema'), dict) for tool in LISTED[product])
        assert listing(product) == LISTED[product] and listing(product) is not LISTED[product]
        free = set(BACKEND_FREE.get(product, '').split())
        assert free <= set(listed)
        assert {name for name, tool in tools_of(product).items() if not tool.requires_backend} == free, product
    for product in ('odoo', 'nextcloud'):  # their private health probes are child tools, never listed
        assert health_probe(product)[0] not in {t['name'] for t in LISTED[product]}


async def child_listing(store, product, seen=None):
    """Raw tools/list straight from the real child (handed to seen first), and the gateway's answer relayed from it."""
    endpoint = Endpoint(product)
    process = endpoint.supervisor((n8n_spec if product == 'n8n' else child_spec)(store.load(), store.directory))
    try:
        await process.start()
        token = store.load().child_token
        async with endpoint.client() as to_child:
            headers = {'Authorization': 'Bearer ' + token, **ACCEPT}
            async with asyncio.timeout(25):
                while True:
                    try:
                        result = await rpc(to_child, endpoint.url, headers, INIT)
                        break
                    except (ValueError, httpx.HTTPError):
                        await asyncio.sleep(.1)
            headers['MCP-Protocol-Version'] = result['protocolVersion']
            await rpc(to_child, endpoint.url, headers, {'jsonrpc': '2.0', 'method': 'notifications/initialized'})
            raw = await rpc(to_child, endpoint.url, headers, {'jsonrpc': '2.0', 'id': 2, 'method': 'tools/list'})
            await to_child.delete(endpoint.url, headers=headers)
            if seen is not None:
                seen(raw)
            _, app = make_apps(store, tools_of(product), to_child, child_url=endpoint.url, listing=listing(product))
            async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url='http://boundary') as client:
                headers = {'Authorization': 'Bearer ' + store.load().token, **ACCEPT}
                await rpc(client, '/mcp', headers, INIT)
                assert not headers['Mcp-Session-Id'].startswith('woow-local-')  # the child's own session
                relayed = await rpc(client, '/mcp', headers, {'jsonrpc': '2.0', 'id': 2, 'method': 'tools/list'})
                await client.delete('/mcp', headers=headers)
        return raw, relayed
    finally:
        await process.stop(); endpoint.close()


async def own_listing(store, product, available):
    """tools/list as the gateway answers it itself (no child is asked: the transport fails every request)."""
    def no_child(request):
        raise AssertionError('no child may be asked')
    async with httpx.AsyncClient(transport=httpx.MockTransport(no_child)) as to_child:
        _, app = make_apps(store, tools_of(product), to_child, listing=listing(product), availability=lambda: available)
        async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url='http://boundary') as client:
            headers = {'Authorization': 'Bearer ' + store.load().token, **ACCEPT}
            await rpc(client, '/mcp', headers, INIT)
            assert headers['Mcp-Session-Id'].startswith('woow-local-')
            return await rpc(client, '/mcp', headers, {'jsonrpc': '2.0', 'id': 2, 'method': 'tools/list'})


@pytest.mark.parametrize('product', FULL_PRODUCTS)
async def test_snapshot_equals_the_real_child(tmp_path, product):
    """The snapshot is exactly what the real child lists with every tool enabled, and the gateway's own tools/list
    answer is exactly the one it relays from that child for the same state."""
    with fake_api() as (url, events, mutations, failures), closing(ProductStore(tmp_path / 'state', product)) as store:
        if product == 'n8n':
            store.update(backend_url=url, backend_key='DUMMY')
        else:
            store.update(connection=connection(product, url))
        def seen(raw):
            if os.environ.get('WOOW_WRITE_TOOL_SNAPSHOT') == '1':
                write_snapshot(product, reduced(product, raw['tools']))
        raw, relayed = await child_listing(store, product, seen)
        assert 'nextCursor' not in raw  # one page: the snapshot is the whole list
        current = reduced(product, raw['tools'])
        assert current == LISTED[product], f'{product}: regenerate tool_snapshot.py (see this module)'
        own = await own_listing(store, product, {'child': 'backoff', 'ready': False, 'backend': 'unknown', 'reason': None})
        assert own == relayed and len(own['tools']) == len(tools_of(product))
        assert mutations == [] and not failures


async def test_the_unconfigured_n8n_child_lists_exactly_the_backend_free_tools(tmp_path):
    with closing(ProductStore(tmp_path / 'state', 'n8n')) as store:
        raw, relayed = await child_listing(store, 'n8n')
    assert {t['name'] for t in raw['tools']} == set(BACKEND_FREE['n8n'].split())
    # The gateway lists the whole surface for it (the snapshot), not the child's seven tools.
    assert [t['name'] for t in relayed['tools']] == [t['name'] for t in LISTED['n8n']]
